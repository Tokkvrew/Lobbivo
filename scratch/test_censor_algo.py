COMPILED_ROOTS = [re.compile(f'^{p}$', re.IGNORECASE) for p in PROFANITY_ROOT_PATTERNS]
COMPILED_PHRASES = [re.compile(p, re.IGNORECASE) for p in TOXIC_PHRASE_PATTERNS]

def normalize_text(text):
    res = []
    for ch in text.lower():
        res.append(HOMOGLYPHS.get(ch, ch))
    return ''.join(res)

def is_word_profane(word):
    norm = normalize_text(word)
    # Strip non-alphanumeric punctuation from ends
    clean_word = re.sub(r'^[^\wа-яё]+|[^\wа-яё]+$', '', norm)
    if not clean_word:
        return False
    if clean_word in WHITELIST_WORDS:
        return False
    
    for r in COMPILED_ROOTS:
        if r.match(clean_word):
            return True
    return False

# Run test cases
passed = 0
failed = 0
for text, should_be_profane in TEST_CASES:
    norm_phrase = normalize_text(text)
    is_profane = False
    
    # Check multi-word phrase
    for pr in COMPILED_PHRASES:
        if pr.search(norm_phrase):
            is_profane = True
            break
            
    # Check words
    if not is_profane:
        words = re.findall(r'[^\s.,!?:;"\'()<>«»\[\]{}]+', text)
        for w in words:
            if is_word_profane(w):
                is_profane = True
                break
                
    if is_profane == should_be_profane:
        passed += 1
    else:
        failed += 1
        print(f"FAILED: '{text}' -> got {is_profane}, expected {should_be_profane}")

print(f"\nRESULTS: Passed {passed}/{len(TEST_CASES)}, Failed {failed}")
