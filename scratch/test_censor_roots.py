import re

legit_words = [
    "победа", "победил", "победитель",
    "пробег", "пробежка", "пробежал",
    "перебежчик", "перебежал",
    "прибежал", "прибедняться",
    "добежал",
    "забег", "забежал",
    "набег", "набежал",
    "убежал", "убежище",
    "выбежал",
    "отбежал",
    "подбежал",
    "разбег", "разбежался",
    "взбесился",
    "избежать", "избежал",
    "оберег", "оберегать",
    "самообман",
    "недобор", "недобежал",
    "тебе", "тебя", "себе", "себя", "себестоимость",
    "хлеб", "хлебный",
    "стебель",
    "ребенок", "ребята",
    "гребля", "погреб",
    "серебро",
    "требовать", "потребность", "потребитель", "употреблять",
    "лебедь",
    "дебет", "дебют"
]

# Note: in words like "победа" -> prefix "по" + "бед" (not "по" + "еб")
# in "пробег" -> "про" + "бег" (not "про" + "еб")
# in "погреб" -> "по" + "греб" (not "по" + "еб")
# in "оберег" -> "об" + "ерег" (starts with "ер", not "еб")

pattern_str = r'^(?:(?:вы|до|за|на|по|пере|при|про|у|недо|само|съ|въ|подъ|отъ|разъ|объ|изъ|взъ)[еёэ]б.*|[еёэ]б[аеиоуыйлнщцчк].*|[еёэ]бл.*|[еёэ]б[оу]т.*|[еёэ]бну.*|[еёэ]б[оыа].*|долб[оа][еёэ]б.*)$'
regex = re.compile(pattern_str, re.IGNORECASE)

false_pos = []
for word in legit_words:
    if regex.match(word):
        false_pos.append(word.encode('ascii', 'backslashreplace').decode('ascii'))

print("False positives count:", len(false_pos), false_pos)
