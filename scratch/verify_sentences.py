def censor(text):
    for phr in TOXIC_PHRASES:
        text = phr.sub(lambda m: f'<span class="censored-word">{m.group(0)}</span>', text)
    
    parts = re.split(r'(<span class="censored-word"[^>]*>.*?</span>)', text, flags=re.DOTALL)
    for i in range(len(parts)):
        if parts[i].startswith('<span class="censored-word"'):
            continue
        
        def replace_word(match):
            raw = match.group(0)
            clean = re.sub(r'^[^\wа-яА-ЯёЁ]+|[^\wа-яА-ЯёЁ]+$', '', raw)
            if not clean:
                return raw
            lower = clean.lower()
            if lower in WHITELIST:
                return raw
            
            norm_leet = ''.join(LEETSPEAK_MAP.get(c, c) for c in lower)
            if norm_leet in WHITELIST:
                return raw
            
            for r in PROFANITY_ROOTS:
                if r.match(norm_leet) or r.match(lower):
                    return f'<span class="censored-word">{raw}</span>'
            return raw
            
        parts[i] = re.sub(r'[^\s.,!?:;"\'()<>«»\[\]{}]+', replace_word, parts[i])
        
    return ''.join(parts)

